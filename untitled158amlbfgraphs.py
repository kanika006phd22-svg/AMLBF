import numpy as np
import matplotlib.pyplot as plt

import matplotlib.pyplot as plt

# Simulated performance metrics for comparison
models = ['AMLBF', 'RL-Routing', 'LEACH-SDN', 'DeepLB']

latency = [210, 290, 320, 270]
lifetime = [18.2, 14.5, 13.0, 15.7]
pdr = [94.7, 88.4, 84.3, 90.1]
ddos_latency = [1.8, 4.5, 6.8, 3.7]

# Create subplots
fig, axs = plt.subplots(2, 2, figsize=(12, 10))
fig.suptitle("Performance Comparison of AMLBF with Existing Models", fontsize=16)

# Plot 1: Latency
axs[0, 0].plot(models, latency, marker='o')
axs[0, 0].set_title('End-to-End Latency (ms)')
axs[0, 0].set_ylabel('Latency (ms)')
axs[0, 0].grid(True)

# Plot 2: Network Lifetime
axs[0, 1].plot(models, lifetime, marker='o')
axs[0, 1].set_title('Network Lifetime (Months)')
axs[0, 1].set_ylabel('Lifetime (months)')
axs[0, 1].grid(True)

# Plot 3: Packet Delivery Ratio
axs[1, 0].plot(models, pdr, marker='o')
axs[1, 0].set_title('Packet Delivery Ratio (%)')
axs[1, 0].set_ylabel('PDR (%)')
axs[1, 0].grid(True)

# Plot 4: DDoS Detection Latency
axs[1, 1].plot(models, ddos_latency, marker='o')
axs[1, 1].set_title('DDoS Detection Latency (s)')
axs[1, 1].set_ylabel('Latency (s)')
axs[1, 1].grid(True)

plt.tight_layout(rect=[0, 0, 1, 0.96])
plt.show()

