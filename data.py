# Step 2: Preprocess the Dataset
def preprocess_data(data):
    """
    Preprocess the CRAWDAD dataset.
    Parameters:
        data: DataFrame - Raw data
    Returns:
        DataFrame - Processed data
    """
    # Original intention: Select relevant columns for SDN-WSN analysis
    # As the current dataset is 'california_housing_train.csv',
    # we'll use analogous columns for demonstration.
    # User will need to replace with actual CRAWDAD data columns.

    processed_data = data.copy()

    # Create dummy node_id and timestamp as they are not in the sample dataset
    processed_data['node_id'] = processed_data.index
    processed_data['timestamp'] = pd.to_datetime('now')

    # Map existing columns to expected CRAWDAD metrics for demonstration
    # Please replace these with actual CRAWDAD column mappings when available
    processed_data['energy'] = processed_data['median_house_value']
    processed_data['delay'] = processed_data['population']
    processed_data['traffic'] = processed_data['total_rooms']

    # Select only the newly mapped columns and the id/timestamp for consistency with original intent
    processed_data = processed_data[["node_id", "timestamp", "energy", "delay", "traffic"]]

    # Fill missing values
    processed_data = processed_data.ffill()

    # Normalize energy, delay, and traffic for consistency
    processed_data["energy"] = processed_data["energy"] / processed_data["energy"].max()
    processed_data["delay"] = processed_data["delay"] / processed_data["delay"].max()
    processed_data["traffic"] = processed_data["traffic"] / processed_data["traffic"].max()

    print("Data preprocessing complete.")
    return processed_data

