# Step 4: Simulate Load Balancing
def simulate_load_balancing(data):
    """
    Simulate a simple load balancing strategy based on node energy and traffic.
    Parameters:
        data: DataFrame - Processed data
    """
    print("Simulating load balancing...")

    # Example strategy: Prefer nodes with higher energy and lower traffic
    data["load_score"] = data["energy"] - data["traffic"]
    balanced_nodes = data.sort_values(by="load_score", ascending=False)

